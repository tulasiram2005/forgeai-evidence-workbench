import fs from 'node:fs';
import {corpora,suites} from '../retrieval/reference-agents.mjs';
import {strictAnswer} from '../public/evidence-first.mjs';
import {stressVerdict} from '../retrieval/stress-judge.mjs';
const observations=[];
for(const suite of [...suites,'holdout4','holdout5']){
 let total=0,passed=0;
 for await(const {name,chunks,cases} of corpora(suite)){
   if(suite==='holdout5'){
     const rows=JSON.parse(fs.readFileSync('evidence/holdout5/'+name+'.json')).filter(r=>r.config==='strict');
     total+=rows.length;passed+=rows.filter(r=>r.passed).length;
   }else for(const c of cases){
     total++;
     passed+=Number(stressVerdict(c,strictAnswer({chunks,retrieval:{threshold:.52},tools:[]},c.question),chunks));
   }
 }
 observations.push({suite,total,passed,actual:passed/total});
}
const mean=a=>a.reduce((s,r)=>s+r.actual,0)/a.length;
for(const r of observations)r.forecast=mean(observations.filter(other=>other!==r));
const candidates=JSON.parse(fs.readFileSync('evidence/holdout5/summary.json')).filter(r=>r.name==='pooled' && ['strict','contextual'].includes(r.config));
const qualified=candidates.some(r=>r.balancedAccuracy>=.6&&r.nearMissFalseAnswers.count/r.nearMissFalseAnswers.total<=.1);
const pilot={qualified,config:'strict',metric:'overall case pass, including correct refusals and clarifications',n:observations.length,forecast:mean(observations),meanAbsoluteError:observations.reduce((s,r)=>s+Math.abs(r.actual-r.forecast),0)/observations.length,observations};
fs.writeFileSync('evidence/holdout5/forecast.json',JSON.stringify(pilot,null,2)+'\n');
fs.writeFileSync('public/forecast-pilot.mjs','// Generated by scripts/forecast.mjs from the committed pilot receipts.\nexport const pilot='+JSON.stringify(pilot,null,2)+';\n');
